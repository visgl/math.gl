import type {ResolvedScaleDescriptor, ScaleColor, ScaleValue} from './scale-types';

/** One backend-independent sampling expectation, before storage-format quantization. */
export type ScaleConformanceSample = Readonly<{
  /** Input value; null represents an invalid source row. */
  input: ScaleValue | null;
  /** Expected numeric value, color channels, or invalid output. */
  expected: number | ScaleColor | null;
}>;

/** Serializable fixture for CPU, worker, and GPU scale implementations. */
export type ScaleConformanceCase = Readonly<{
  /** Stable descriptive case identifier. */
  id: string;
  /** Resolved domain, range, class breaks, and color interpretation. */
  descriptor: ResolvedScaleDescriptor;
  /** Maximum absolute error per numeric component, including alpha. */
  absoluteTolerance: number;
  /** Independently specified expected values, not generated by the sampler under test. */
  samples: readonly ScaleConformanceSample[];
}>;

