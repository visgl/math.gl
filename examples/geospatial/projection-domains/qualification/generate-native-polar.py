"""Generate MIT-licensed synthetic EPSG:3031 point-sampled raster tiles.
No observational data or external dependencies. Run from this directory.
"""
import base64, hashlib, json, math
from pathlib import Path
step=125000
tiles=[]
for index in range(2):
    data=bytearray()
    for row in range(65):
        for column in range(33):
            gx=index*32+column
            x=-4000000+gx*step
            y=-4000000+row*step
            data.extend([round(gx/64*255),round(row/64*255),224 if (gx//4+row//4)%2 else 64,0 if math.hypot(x,y)<500000 else 255])
    tiles.append(dict(id=['west','east'][index],width=33,height=65,
        affine=[-4000000+index*4000000,step,0,-4000000,0,step],
        rgbaBase64=base64.b64encode(data).decode(),sha256=hashlib.sha256(data).hexdigest()))
result=dict(schemaVersion=1,authority='EPSG:3031',definition='+proj=stere +lat_0=-90 +lat_ts=-71 +lon_0=0 +datum=WGS84 +units=m',
    sampling='point samples, including shared boundary nodes; not pixel areas',
    provenance='Synthetic coordinate ramp and checker pattern generated by generate-native-polar.py; not observed imagery or elevation',
    license='MIT',nodata='alpha=0 within 500 km of the pole',tiles=tiles)
Path(__file__).with_name('native-polar.json').write_text(json.dumps(result,indent=2)+'\n')
