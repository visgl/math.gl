import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {mkdtemp, mkdir, readFile, writeFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

// Fetch published artifacts without running upstream install/build scripts.
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const toolsRequire = createRequire(require.resolve('@vis.gl/dev-tools'));
const {build} = toolsRequire('esbuild');
const directory = await mkdtemp(join(tmpdir(), 'math-gl-vendor-'));
const packages = [
  ['jsep', '1.4.0', 'jsep', 'B7qPcEVE3NVkmSJbaYxvv4cHkVW7DQsZz13pUMrfS8z8Q/BuShN+gcTXrUlPiGqM2/t/EEaI030bpxMqY8gMlw=='],
  ['@js-temporal/polyfill', '0.5.1', 'polyfill', 'hloP58zRVCRSpgDxmqCWJNlizAlUgJFqG2ypq79DCvyv9tHjRYMDOcPFjzfl/A1/YxDvRCZz8wvZvmapQnKwFQ=='],
  ['jsbi', '4.3.2', 'jsbi', '9fqMSQbhJykSeii05nxKl4m6Eqn2P6rOlYiS+C5Dr/HPIU/7yZxu5qzbs40tgaFORiw2Amd0mirjxatXYMkIew=='],
  ['@photostructure/tz-lookup', '11.7.0', 'tz-lookup', 'QbKHXvleluMIlAHf2JiQTJNU5rLQBeQhLobyRqgXZ6NNGKqNikaRkjYviJ4nMU7Y75QE7bBYM8xjiFGjAukyhw==']
];
const jsepHeader = '// SPDX-License-Identifier: MIT\n// SPDX-FileCopyrightText: Copyright (c) 2013 Stephen Oney\n';
const temporalHeader = '// SPDX-License-Identifier: ISC AND Apache-2.0\n// SPDX-FileCopyrightText: Copyright 2017, 2018, 2019, 2020 ECMA International\n// SPDX-FileCopyrightText: the V8 project authors\n';
const lookupHeader = '// SPDX-License-Identifier: CC0-1.0\n// SPDX-FileCopyrightText: PhotoStructure, Inc. and tz-lookup contributors\n';
const jsepDir = 'modules/core/src/expressions/vendor/jsep';
const temporalDir = 'modules/earth/src/timezone/vendor/temporal';
const lookupDir = 'modules/earth/src/timezone/vendor/tz-lookup';
async function save(path, contents) {
  await mkdir(join(root, path, '..'), {recursive: true});
  await writeFile(join(root, path), contents);
}
async function license(path, source, header) {
  await save(path, header.replaceAll('// ', '') + '\n' + await readFile(join(directory, source, 'LICENSE'), 'utf8'));
}
async function bundle(path, entry, header) {
  const result = await build({
    absWorkingDir: directory,
    stdin: {contents: entry, resolveDir: directory, sourcefile: 'vendor-entry.js'},
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2020',
    mainFields: ['module', 'main'],
    alias: {jsbi: join(directory, 'jsbi/dist/jsbi.mjs')},
    write: false,
    legalComments: 'inline',
    metafile: true
  });
  assert(Object.values(result.metafile.outputs).every(output => output.imports.length === 0));
  // Keep third-party runtime JS intact, with a typed boundary for our TS wrappers.
  const text = result.outputFiles[0].text.replace(/^\/\/ .*vendor-entry\.js$/gm, '// vendor-entry.js').replace(/export \{\s*([\w$]+) as default\s*\};\s*$/, 'export default $1 as any;\n');
  assert(text.includes(' as any;'), 'Expected a single default export');
  await save(path, header + '// @ts-nocheck\n// Generated by scripts/vendor-expression-timezone-deps.mjs; see README.md and LICENSE files.\n\n' + text);
}
try {
  for (const [name, version, shortName, integrity] of packages) {
    const response = await fetch(`https://registry.npmjs.org/${name}/-/${shortName}-${version}.tgz`);
    assert(response.ok, `${name}: HTTP ${response.status}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    assert.equal(createHash('sha512').update(bytes).digest('base64'), integrity, `${name}: tarball integrity`);
    const archive = join(directory, shortName + '.tgz');
    await writeFile(archive, bytes);
    await mkdir(join(directory, shortName));
    execFileSync('tar', ['-xzf', archive, '--strip-components=1', '-C', join(directory, shortName)]);
  }
  await bundle(jsepDir + '/runtime.ts', "export {default} from './jsep/dist/jsep.js';", jsepHeader);
  const jsepTypes = (await readFile(join(directory, 'jsep/typings/tsd.d.ts'), 'utf8'))
    .replace(/^declare module 'jsep' \{\s*/, '')
    .replace(/\s*export = jsep;\s*\}\s*$/, '\nexport type {jsep as Jsep};\n')
    .replace(/^namespace jsep/m, 'declare namespace jsep')
    .replace(/^\tfunction jsep/m, 'declare function jsep');
  await save(jsepDir + '/types.ts', jsepHeader + '\n' + jsepTypes);
  await license(jsepDir + '/LICENSE.txt', 'jsep', jsepHeader);
  await bundle(temporalDir + '/runtime.ts', "export {Temporal as default} from './polyfill/dist/index.esm.js';", temporalHeader);
  const temporalTypes = (await readFile(join(directory, 'polyfill/index.d.ts'), 'utf8')).split('declare namespace Intl')[0].replace('export namespace Temporal', 'export declare namespace Temporal');
  await save(temporalDir + '/types.ts', '// SPDX-License-Identifier: ISC\n// SPDX-FileCopyrightText: Copyright 2017, 2018, 2019, 2020 ECMA International\n\n' + temporalTypes.trimEnd() + '\n');
  await license(temporalDir + '/LICENSE.txt', 'polyfill', '// SPDX-License-Identifier: ISC\n// SPDX-FileCopyrightText: Copyright 2017, 2018, 2019, 2020 ECMA International\n');
  await license(temporalDir + '/JSBI-LICENSE.txt', 'jsbi', '// SPDX-License-Identifier: Apache-2.0\n// SPDX-FileCopyrightText: the V8 project authors\n');
  await bundle(lookupDir + '/runtime.ts', "export {default} from './tz-lookup/tz.js';", lookupHeader);
  await license(lookupDir + '/LICENSE.txt', 'tz-lookup', lookupHeader);
} finally {
  await rm(directory, {recursive: true, force: true});
}
